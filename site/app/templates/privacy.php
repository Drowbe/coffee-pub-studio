    <h1>Privacy policy</h1>
    <p class="muted" style="margin-top:0">Coffee Pub Studio &middot; last updated October 14, 2026</p>
<div class="narrow">
<p>
    Coffee Pub Studio is a desktop application that runs on your own computer. It does not
    have an account system, a server of its own, advertising, or analytics, and it does not
    send information to Coffee Pub. The only places it connects are ones you set up yourself:
    your own OBS, your own Coffee Pub Tavern server, and, if you turn it on, Google's YouTube
    service.
  </p>

  <h2>What is stored, and where</h2>
  <p>
    Everything Studio stores stays on your computer, in the application's own data folder:
    your settings, and the passwords and sign-in tokens you give it (for OBS, Coffee Pub Tavern
    and YouTube). Passwords and tokens are encrypted with your operating system's keychain.
  </p>

  <h2>YouTube and Google user data</h2>
  <p>
    If you choose to turn on YouTube upload, Studio asks Google for one permission:
    <code>https://www.googleapis.com/auth/youtube.upload</code>, which lets it upload videos to
    the YouTube channel you sign in with. It cannot read, change or delete your existing videos,
    comments, playlists or account information.
  </p>
  <ul>
    <li><strong>What it accesses:</strong> only the ability to upload. Studio receives a sign-in token from Google when you approve the request.</li>
    <li><strong>What it stores:</strong> that token, encrypted on your computer. It is never sent anywhere except back to Google.</li>
    <li><strong>What it sends:</strong> when an automation you configured runs, the recording file you chose and its title, description, category and visibility are sent directly from your computer to YouTube.</li>
    <li><strong>What it shares:</strong> nothing. Google user data is not sold, shared with anyone, or used for advertising or any purpose other than the uploads you request.</li>
  </ul>
  <p>
    Coffee Pub Studio's use and transfer of information received from Google APIs adheres to the
    <a href="https://developers.google.com/terms/api-services-user-data-policy">Google API Services User Data Policy</a>,
    including the Limited Use requirements.
  </p>

  <h2>Revoking access and deleting data</h2>
  <p>
    Click <strong>Disconnect</strong> on the YouTube card in Studio to delete the stored token from
    your computer. You can also remove Studio's access at any time from your Google Account's
    <a href="https://myaccount.google.com/permissions">third-party access</a> page. Uninstalling
    the app and deleting its data folder removes everything else.
  </p>

  <h2>Changes and contact</h2>
  <p>
    If this policy changes, the date above will change with it. Questions can be raised on the
    <a href="https://github.com/Drowbe/coffee-pub-studio/issues">project's issue tracker</a>.
  </p>
